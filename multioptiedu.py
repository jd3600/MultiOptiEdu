import numpy as np

def find_divisors(number):
    """
    Returns the set of all divisors of a given number.
    """
    divisors = set()
    for i in range(1, int(np.sqrt(number)) + 1):
        if number % i == 0:
            divisors.add(i)
            divisors.add(number // i)
    return divisors

def display_divisors_table(numbers, divisors_lists):
    """
    Displays a text table showing the divisors of several numbers.
    The columns correspond to the unique divisors of all numbers.
    """
    # Combine and sort all unique divisors for the table columns
    all_divisors = set()
    for d_set in divisors_lists:
        all_divisors.update(d_set)
    all_divisors = sorted(list(all_divisors))

    # Prepare the rows for display
    rows = []
    rows.append(["Number"] + [str(d) for d in all_divisors])  # Header row

    for i, number in enumerate(numbers):
        current_divisors = divisors_lists[i]
        data_row = [str(number)] + [" X " if d in current_divisors else "   " for d in all_divisors]
        rows.append(data_row)

    # Determine column widths for aligned display
    widths = [max(len(item) for item in col_items) for col_items in zip(*rows)]

    # Display the table
    border = " | ".join("-" * width for width in widths)

    print(border)
    print(" | ".join(col.ljust(width) for col, width in zip(rows[0], widths)))
    print(border)
    for row in rows[1:]:
        print(" | ".join(col.ljust(width) for col, width in zip(row, widths)))
    print(border)

