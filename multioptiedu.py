try:
    print("GCD search program for multiple numbers (type '/' to finish input).\n")
    entered_numbers = []
    while True:
        entry = input(f"Please enter number #{len(entered_numbers) + 1}: ")
        if entry == '/':
            if len(entered_numbers) < 2:
                print("Please enter at least two numbers to calculate the GCD.")
                entered_numbers = []
                continue
            break

        value = int(entry)
        if value <= 0:
            print("Please enter a positive integer.")
        else:
            entered_numbers.append(value)

    # 1. Find the divisors for each entered number
    divisors_lists = [find_divisors(number) for number in entered_numbers]

    # 2. Identify common divisors and the GCD
    common_divisors = set.intersection(*divisors_lists)
    gcd = max(common_divisors) if common_divisors else None

    # 3. Display the table and the result
    print("\n--- Divisor Analysis Table ---")
    display_divisors_table(entered_numbers, divisors_lists)

    print("\n--- Final Result ---")
    if gcd is not None:
        print(f"Common divisors: {sorted(list(common_divisors))}")
        print(f"The Greatest Common Divisor (GCD) is: {gcd}")
    else:
        print("No common divisor found other than 1.")

except ValueError:
    print("Invalid input. Please enter only integers or '/'.")